#!/usr/bin/env bash
set -Eeuo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"
fail(){ echo "ANDROID BUILD BLOCKED: $*" >&2; exit 2; }
for c in node npm java curl unzip sha256sum; do command -v "$c" >/dev/null 2>&1 || fail "$c is required"; done
SDK_ROOT="${ANDROID_SDK_ROOT:-${ANDROID_HOME:-$HOME/Android/Sdk}}"
export ANDROID_HOME="$SDK_ROOT" ANDROID_SDK_ROOT="$SDK_ROOT"
SDK_READY=1
for item in platforms/android-35/android.jar build-tools/35.0.0/apksigner build-tools/35.0.0/aapt platform-tools/adb; do
  [[ -e "$SDK_ROOT/$item" ]] || SDK_READY=0
done
if [[ "$SDK_READY" != 1 ]]; then
  [[ "${CALCULATOR_AUTO_INSTALL_ANDROID_SDK:-1}" == 1 ]] || fail "Required SDK components are missing at $SDK_ROOT."
  bash scripts/bootstrap-android-sdk.sh
fi
if [[ ! -x node_modules/.bin/cap ]]; then
  npm_config_fetch_retries=2 npm_config_fetch_retry_mintimeout=1000 npm_config_fetch_retry_maxtimeout=8000 npm install --no-audit --no-fund
fi
npm test
npm run build
if [[ ! -d android ]]; then npx cap add android; fi
npx cap sync android
[[ -s android/gradle/wrapper/gradle-wrapper.properties ]] || fail 'Gradle wrapper configuration was not generated by Capacitor.'
chmod +x android/gradlew
(cd android && ./gradlew --no-daemon --stacktrace assembleDebug)
APK="$ROOT/android/app/build/outputs/apk/debug/app-debug.apk"
[[ -s "$APK" ]] || fail "APK was not produced at $APK"
APKSIGNER="$SDK_ROOT/build-tools/35.0.0/apksigner"
AAPT="$SDK_ROOT/build-tools/35.0.0/aapt"
"$APKSIGNER" verify --verbose "$APK"
unzip -t "$APK" >/dev/null
ENTRIES="$(unzip -Z1 "$APK")"
grep -Fx 'AndroidManifest.xml' <<<"$ENTRIES" >/dev/null || fail 'AndroidManifest.xml missing'
grep -E '^classes([0-9]+)?\.dex$' <<<"$ENTRIES" >/dev/null || fail 'classes.dex missing'
BADGING="$("$AAPT" dump badging "$APK")"
grep -F "package: name='app.calculator.offline'" <<<"$BADGING" >/dev/null || fail 'package ID mismatch'
grep -F "application-label:'Calculator'" <<<"$BADGING" >/dev/null || fail 'application label mismatch'
sha256sum "$APK"
echo "APK_BUILD_RESULT=SUCCESS"
echo "APK_TYPE=DEBUG_TESTING_SIDELOAD_ONLY"
echo "APK_PACKAGE_ID=app.calculator.offline"
echo "APK_LABEL=Calculator"
echo "APK_PATH=$APK"
